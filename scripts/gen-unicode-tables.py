"""Writes src/indra/unicode-data.ts and tests/fixtures/golden/unicode-sample.json.

JavaScript has no API for Unicode bidi classes or East Asian width, so the port
reads range tables made from the reference interpreter (Python 3.12, Unicode
15.0.0). Run it by hand from the repo root:

    uvx --from indra-ocr==1.1.1 python -I scripts/gen-unicode-tables.py
"""

import json
import random
import unicodedata as ud
from pathlib import Path

from indra_ocr.rtl import (
    brackets_as_shapes,
    flip,
    label_from_visual,
    normalize,
    rtl_base,
    visual_label,
)

ROOT = Path(__file__).resolve().parent.parent
MAX = 0x110000
HEADER = """\
// SPDX-License-Identifier: Apache-2.0
// Copyright (c) 2026 PT Perkasa Pilar Utama
//
// GENERATED by scripts/gen-unicode-tables.py from Unicode {ver} (Python {py}).
// Do not edit by hand: change the script and run it again.
//
// Each table is a run of "gap len class" triples in base 36, space separated:
// a range starts gap code points after the end of the previous range and spans
// len + 1 code points.
"""


def ranges(f):
    out, prev = [], None
    for cp in range(MAX):
        v = f(chr(cp))
        if prev and v and prev[2] == v and prev[1] == cp - 1:
            prev[1] = cp
        elif v:
            prev = [cp, cp, v]
            out.append(prev)
        else:
            prev = None
    return out


def b36(n):
    s = ""
    while True:
        n, r = divmod(n, 36)
        s = "0123456789abcdefghijklmnopqrstuvwxyz"[r] + s
        if not n:
            return s


def encode(rs):
    toks, end = [], -1
    for a, b, v in rs:
        toks += [b36(a - end - 1), b36(b - a), b36(v)]
        end = b
    text = " ".join(toks)
    chunks = [text[i : i + 88] for i in range(0, len(text), 88)]
    return "\n".join(f'  "{c}"' for c in chunks)


def cls(c):
    b = ud.bidirectional(c)
    if b in ("R", "AL"):
        return 1  # strong right to left
    if b == "L":
        return 2
    if b in ("EN", "AN"):
        return 3  # digits
    if ud.category(c) in ("Mn", "Me"):
        return 4  # combining mark (bidi class NSM, so it never clashes)
    return 0


def wide(c):
    return 1 if ud.east_asian_width(c) in "WF" else 0


def write_ts():
    bidi, eaw = ranges(cls), ranges(wide)
    head = HEADER.format(ver=ud.unidata_version, py="3.12")
    body = (
        f"\n/** Classes: 1 right to left (R, AL), 2 L, 3 digit (EN, AN), 4 mark (Mn, Me). */\n"
        f"export const BIDI_TABLE: string =\n{encode(bidi)};\n"
        f"\n/** East Asian width W or F, class 1. */\n"
        f"export const WIDE_TABLE: string =\n{encode(eaw)};\n"
    )
    path = ROOT / "src/indra/unicode-data.ts"
    path.write_text(head + body.replace('"\n  "', '" +\n  "'), encoding="ascii")
    print(path, path.stat().st_size, "bytes;", len(bidi), "bidi ranges,", len(eaw), "wide ranges")


def fixture():
    rng = random.Random(0)
    spans = [(0x0590, 0x08FF), (0xFB1D, 0xFDFF), (0xFE70, 0xFEFF)]
    cps = {cp for a, b in spans for cp in range(a, b + 1)}
    while len(cps) < 3000:
        cps.add(rng.randrange(0, 0x10000))
    while len(cps) < 4000:
        cps.add(rng.randrange(0x10000, MAX))
    # CJK, Hangul and fullwidth edges for display_len.
    cps |= {0x1100, 0x115F, 0x2E80, 0x3000, 0x4E00, 0x9FFF, 0xAC00, 0xFF01, 0xFF60, 0xFFE0}
    cps = sorted(c for c in cps if not 0xD800 <= c <= 0xDFFF)
    chars = [
        [cp, ud.bidirectional(chr(cp)), ud.east_asian_width(chr(cp)), ud.category(chr(cp))]
        for cp in cps
    ]

    def pick(a, b):
        return [chr(c) for c in range(a, b + 1)]

    he = pick(0x5D0, 0x5EA)
    niqqud = pick(0x5B0, 0x5BC) + ["\u05bf"]
    ar = pick(0x621, 0x64A)
    harakat = pick(0x64B, 0x652)
    pres = pick(0xFB50, 0xFB60) + pick(0xFB1D, 0xFB2A) + pick(0xFE70, 0xFEFC) + pick(0xFDF2, 0xFDFB)
    groups = [
        (he, 6), (niqqud, 2), (ar, 6), (harakat, 2), (pres, 2), (["\u0640"], 1),
        (pick(0x660, 0x669), 1), (list("abcdefXYZ"), 4), (list("0123456789"), 2),
        (list("()[]{}<>"), 2), (["\u00ab", "\u00bb", "\u2039", "\u203a"], 1),
        (list("  .,:-/"), 3), (["\u4e2d", "\uff21", "\U0001f600", "\u0301"], 1),
    ]
    pool = [c for g, w in groups for c in g]
    weights = [w for g, w in groups for c in g]
    strings = [
        "", "abc", "\u05e9\u05dc\u05d5\u05dd", "\u0645\u0631\u062d\u0628\u0627",
        "\u0645\u0631\u062d\u0628\u0627 2026-10-13 \u05e9\u05dc\u05d5\u05dd abc def",
        "the word \u05e9\u05dc\u05d5\u05dd means peace", "\u0301\u05d0", "\u05d0(\u05d1)[\u05d2]",
        "\u0640\u0640\u0645",
    ]
    for _ in range(170):
        n = rng.randint(1, 40)
        strings.append("".join(rng.choices(pool, weights=weights, k=n)))
    rows = []
    for s in strings:
        rows.append(
            {
                "s": s,
                "flip": flip(s),
                "flipNoMirror": flip(s, mirror=False),
                "flipRtl": flip(s, base_rtl=True),
                "flipLtr": flip(s, base_rtl=False),
                "normalize": normalize(s),
                "rtlBase": rtl_base(s),
                "visualLabel": visual_label(s),
                "visualLabelRtl": visual_label(s, base_rtl=True),
                "labelFromVisual": label_from_visual(s),
                "labelFromVisualShapes": label_from_visual(s, shapes=True),
            }
        )
    cands = [s for s in strings if s]
    lists = []
    for _ in range(40):
        lists.append([rng.choice(cands) for _ in range(rng.randint(0, 6))])
    lists += [
        ["\u05d0(\u05d1"], ["\u05d0)\u05d1"], ["\u05d0(\u05d1", "\u05d0)\u05d1"],
        ["\u05d0)\u05d1", "\u05d0(\u05d1", "\u05d0)\u05d1"], [],
    ]
    brackets = [{"lines": ls, "shapes": brackets_as_shapes(ls)} for ls in lists]
    out = {"unicode": ud.unidata_version, "chars": chars, "strings": rows, "brackets": brackets}
    path = ROOT / "tests/fixtures/golden/unicode-sample.json"
    path.write_text(json.dumps(out, ensure_ascii=True, separators=(",", ":")), encoding="ascii")
    print(path, path.stat().st_size, "bytes;", len(chars), "chars,", len(rows), "strings")


if __name__ == "__main__":
    write_ts()
    fixture()
